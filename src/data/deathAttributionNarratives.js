// =============================================
// Attribution Classifier
// =============================================

/**
 * Classify death attribution from death context + state.
 * Maps death types to one of 5 attribution categories.
 *
 * Rules:
 *   - mode === 'san' → cognitive_collapse
 *   - death_hint === 'event' / tags含 event_forced → became_the_event
 *   - starvation/infection with food≤0 → consumed_by_city
 *   - NPC 背叛: tags含 traitor + npcTrust minimum归零 → sacrificed_by_city
 *   - Suicide behavior tags (death_choice, surrender) → surrendered_to_world
 *   - Fallback: mode-based (san→cognitive, hp→consumed)
 *
 * @param {object} deathCtx  - from resolveDeath()
 * @param {object} state    - game state
 * @returns {string} attribution category key
 */
export function classifyDeathAttribution(deathCtx, state) {
  const type = deathCtx.type;
  const mode = deathCtx.mode;
  const srcEvt = deathCtx.sourceEventId;

  // ── 1. 自杀行为 ─────────────────────────────
  // Tags 含 death_choice / surrender / self_inflicted
  const suicideTags = ['death_choice', 'surrender', 'self_inflicted', 'suicide_behavior'];
  const allTags = srcEvt ? (state.seenEventTags?.[srcEvt] || []) : [];
  if (allTags.some((t) => suicideTags.includes(t))) {
    return 'surrendered_to_world';
  }

  // ── 2. 成为事件 ─────────────────────────────
  // death_hint === 'event' 或 tags 含 event_forced / becomes_event
  if (type === 'becomes_event' || type === 'loop_collapse') {
    return 'became_the_event';
  }
  if (allTags.some((t) => ['event_forced', 'becomes_event', 'death_as_event'].includes(t))) {
    return 'became_the_event';
  }

  // ── 3. NPC 背叛 ─────────────────────────────
  // Tags 含 traitor / npc_betrayal + npcTrust 最低值归零
  if (allTags.some((t) => ['traitor', 'npc_betrayal', 'npc_abandon'].includes(t))) {
    // Check if minimum NPC trust is 0 (all NPCs abandoned)
    const trusts = Object.values(state.npcTrust || {});
    const hasZeroTrust = trusts.some((v) => v === 0);
    if (hasZeroTrust) {
      return 'sacrificed_by_city';
    }
  }
  // NPC betrayal fallback: any trust 0 + betrayal hint
  const trusts2 = Object.values(state.npcTrust || {});
  if (trusts2.some((v) => v === 0) && type === 'bleeding') {
    return 'sacrificed_by_city';
  }

  // ── 4. 被消食 (饥饿/匮乏) ────────────────────
  if (mode === 'hp' && (type === 'starvation' || type === 'infection')) {
    return 'consumed_by_city';
  }
  if (type === 'starvation' || (state.food != null && state.food <= 0)) {
    return 'consumed_by_city';
  }

  // ── 5. 认知崩塌 (SAN) ───────────────────────
  if (mode === 'san') {
    return 'cognitive_collapse';
  }

  // ── Fallback ─────────────────────────────────
  if (mode === 'hybrid') {
    return 'cognitive_collapse';
  }
  // HP fallback: use consumed_by_city for world-rejection feel
  return 'consumed_by_city';
}
